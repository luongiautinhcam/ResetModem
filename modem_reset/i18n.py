class Translator:
    def __init__(self, language: str = DEFAULT_LANGUAGE):
        self.language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE

    def set_language(self, language: str) -> None:
        self.language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE

    def text(self, key: str, **values: object) -> str:
        template = TRANSLATIONS[self.language].get(
            key,
            TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key),
        )
        return template.format(**values) if values else template

    def status_text(self, status: str) -> str:
        if not isinstance(status, str):
            return str(status)
        key, separator, detail = status.partition(":")
        if key not in TRANSLATIONS[DEFAULT_LANGUAGE]:
            return status
        if not separator:
            return self.text(key)
        if key == "status_reset_auto_start":
            return self.text(key, seconds=detail)
        return self.text(key, detail=self.status_text(detail))
